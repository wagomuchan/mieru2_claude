// { 0: [...], 2: [...] } のような表から、いまの phase に あうものを えらぶ
function byPhase(table) {
  let best = null;
  for (const k of Object.keys(table).map(Number).sort((a, b) => a - b)) if (game.phase >= k) best = table[k];
  return best;
}

function baseTiles() {
  const g = Array.from({ length: H }, () => Array(W).fill('g'));
  const fill = (x, y, w, h, c) => {
    for (let j = y; j < y + h; j++) for (let i = x; i < x + w; i++) {
      if (j >= 0 && j < H && i >= 0 && i < W) g[j][i] = c;
    }
  };
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    if (y >= 31 || (x >= 40 && y >= 12)) g[y][x] = '~';
  }
  fill(34, 24, 6, 9, 'g');      // 灯台の みさき
  fill(40, 25, 2, 6, 'g');
  fill(0, 28, 21, 3, 's');      // 砂浜
  fill(21, 27, 13, 4, 'c');     // 岸壁
  fill(25, 31, 3, 6, 'p');      // 大きい桟橋
  fill(30, 31, 2, 3, 'p');      // 小さい桟橋
  fill(14, 4, 15, 8, 'd');      // 北のひろば（一座が テントをはる）
  fill(20, 1, 3, 26, 'c');      // 道
  fill(3, 14, 35, 2, 'c');
  fill(3, 22, 34, 2, 'c');
  fill(36, 24, 2, 3, 'd');      // 灯台への小道
  fill(4, 7, 1, 7, 'd');        // シメールの家への小道
  fill(13, 16, 17, 6, 'c');     // 市場のひろば
  for (const [x, y] of [[2, 10], [6, 11], [11, 6], [12, 12], [30, 4], [35, 5], [37, 9], [8, 20], [33, 20], [2, 27], [36, 30], [39, 26], [16, 13], [27, 13]]) {
    if (g[y][x] === 'g') g[y][x] = 'f';
  }
  return g;
}

