// 3人の ころは 一章と 同じ。 4人に なったら、 6組から えらぶ。
const PAIRS3 = [['shimeru', 'elesia'], ['shimeru', 'meina'], ['elesia', 'meina']];
const ROOMS = [
  [['shimeru', 'elesia'], ['meina', 'sakura']],
  [['shimeru', 'meina'], ['elesia', 'sakura']],
  [['shimeru', 'sakura'], ['elesia', 'meina']],
];
const roomLabel = r => r.map(([x, y]) => `${NAMES[x]}・${NAMES[y]}`).join(' ／ ');
const levelOf = pk => (pk.includes('sakura') ? 2 : game.phase >= PH.FACTORY ? 2 : 1);

async function restAtTent(a) {
  const p = await a.ask(['テントで 休む？'], ['休む', 'やめる']);
  if (p !== 0) return;
  const four = game.partyIds.includes('sakura');
  const pairs = four ? PAIRS4 : PAIRS3;

  // ふたりのおはなし
  const ready = pairs.filter(([x, y]) => {
    const pk = pairKey(x, y);
    return OHANASHI[pk] && !a.has('oh_' + pk) && hearts(x, y) >= (pk.includes('sakura') ? 1 : 2);
  });
  if (ready.length) {
    const [x, y] = ready[0];
    const pk = pairKey(x, y);
    const o = await a.ask([`${NAMES[x]}と ${NAMES[y]}の 「ふたりのおはなし」が あるよ。`, '見る？'], ['見る', 'あとで']);
    if (o === 0) {
      a.flag('oh_' + pk);
      await a.fade(true);
      a.tint('evening');
      await a.wait(300);
      await a.fade(false);
      await a.say([`―― ふたりのおはなし 「${OHANASHI[pk].title}」 ――`, ...OHANASHI[pk].lines, nakaUp(x, y)]);
      addNaka(x, y, 10);
      await a.fade(true);
      a.tint(null);
      await a.wait(300);
      await a.fade(false);
    }
  }

  // 自由時間
  const ft = await a.ask(['ねるまえの 自由時間。', 'だれと だれが いっしょに すごす？'], [...pairs.map(label), 'みんなで すごす']);
  await a.fade(true);
  a.tint('evening');
  await a.wait(300);
  await a.fade(false);
  if (ft < pairs.length) {
    const [x, y] = pairs[ft];
    const pk = pairKey(x, y);
    await a.say([...FREE_TIME[pk][levelOf(pk)], nakaUp(x, y)]);
    addNaka(x, y, 3);
  } else {
    await a.say(four ? FREE_ALL4 : FREE_ALL3);
  }

  // へやわり
  let rooms;
  if (four) {
    const r = await a.ask(['へやわり。 ふたりずつ、 ふたつの テントで ねるよ。'], ROOMS.map(roomLabel));
    rooms = ROOMS[r];
  } else {
    const r = await a.ask(['へやわり。 だれと だれが 同じ テントで ねる？', '（のこりの ひとりは、 ピピたちと ねるよ）'], PAIRS3.map(label));
    rooms = [PAIRS3[r]];
  }
  await a.fade(true);
  a.tint('night');
  await a.wait(300);
  await a.fade(false);
  for (let i = 0; i < rooms.length; i++) {
    const [x, y] = rooms[i];
    const pk = pairKey(x, y);
    addNaka(x, y, 5);
    const key = `c2|${pk}|${levelOf(pk)}`;
    if (i > 0) await a.say(['……となりの テントでは。']);
    if (!game.bedTalks[key]) { game.bedTalks[key] = true; await a.say([...BED_TALK[pk][levelOf(pk)], nakaUp(x, y)]); }
    else await a.say(BED_AGAIN[pk]);
  }

  await a.fade(true);
  a.tint(game.phase === PH.FAIR ? 'night' : null);
  a.restHere();
  await a.wait(500);
  await a.fade(false);
  await a.say([game.phase === PH.FAIR ? 'すこし ねむって、 まつりに もどった。' : '朝に なった。', 'HPと MPが ぜんぶ かいふくした！ おうえんも 3回に もどった！']);
  await askSave(a);
}

